#Разработай систему управления учетными записями пользователей для небольшой компании.
# Компания разделяет сотрудников на обычных работников и администраторов. У каждого сотрудника
# есть уникальный идентификатор (ID), имя и уровень доступа. Администраторы, помимо обычных данных
# пользователей, имеют дополнительный уровень доступа и могут добавлять или удалять пользователя из системы.

#Требования:

#1.Класс `User*: Этот класс должен инкапсулировать данные о пользователе: ID, имя и уровень доступа
# ('user' для обычных сотрудников).

#2.Класс Admin: Этот класс должен наследоваться от класса User. Добавь дополнительный атрибут уровня
# доступа, специфичный для администраторов ('admin'). Класс должен также содержать методы add_user и
# remove_user, которые позволяют добавлять и удалять пользователей из списка (представь, что это просто
# список экземпляров User).

#3.Инкапсуляция данных: Убедись, что атрибуты классов защищены от прямого доступа и модификации снаружи.
# Предоставь доступ к необходимым атрибутам через методы (например, get и set методы).

# Класс обычного пользователя
class User:
    def __init__(self, user_id, name):
        """Инициализация пользователя
        Args:
            user_id (int): Уникальный идентификатор
            name (str): Имя пользователя
        """
        self._user_id = user_id  # Защищенный атрибут ID
        self._name = name  # Защищенный атрибут имени
        self._access_level = 'user'  # Уровень доступа по умолчанию

    @property
    def user_id(self):
        """Геттер для получения ID пользователя"""
        return self._user_id

    @property
    def name(self):
        """Геттер для получения имени пользователя"""
        return self._name

    @property
    def access_level(self):
        """Геттер для получения уровня доступа"""
        return self._access_level

    def __str__(self):
        """Строковое представление пользователя"""
        return f"Пользователь: ID={self.user_id}, Имя='{self.name}', Уровень='{self.access_level}'"


# Класс администратора (наследуется от User)
class Admin(User):
    def __init__(self, user_id, name):
        """Инициализация администратора"""
        super().__init__(user_id, name)  # Вызов конструктора родительского класса
        self._access_level = 'admin'  # Повышаем уровень доступа
        self._users_list = []  # Список пользователей системы

    def add_user(self, user):
        """Добавление нового пользователя в систему
        Args:
            user (User): Объект пользователя для добавления
        """
        if not isinstance(user, User):
            print("Ошибка: можно добавлять только объекты класса User")
            return

        # Проверяем, нет ли уже пользователя с таким ID
        if any(u.user_id == user.user_id for u in self._users_list):
            print(f"Ошибка: пользователь с ID {user.user_id} уже существует")
            return

        self._users_list.append(user)
        print(f"Добавлен пользователь: {user.name} (ID: {user.user_id})")

    def remove_user(self, user_id):
        """Удаление пользователя из системы
        Args:
            user_id (int): ID пользователя для удаления
        """
        # Ищем пользователя по ID
        for i, user in enumerate(self._users_list):
            if user.user_id == user_id:
                deleted_name = user.name
                del self._users_list[i]
                print(f"Пользователь {deleted_name} (ID: {user_id}) удален")
                return
        print(f"Ошибка: пользователь с ID {user_id} не найден")

    def list_users(self):
        """Вывод списка всех пользователей"""
        print("\nТекущий список пользователей:")
        if not self._users_list:
            print("Система не содержит пользователей")
            return

        for user in self._users_list:
            print(f"  - {user}")


